/**
 * Local Persistence Format (.cmn / JSON) Contract
 * Based on MASTER_SPEC.md (Section 5.3) and DECISION_RATIONALE.md (Section 4.1)
 */

import { VisualAST } from "./visualAst";
import { CompiledCognitiveMap } from "./compiledGraph";

/**
 * Atomic Vector Point captured from digital pen hardware (Wacom EMR / Apple Pencil)
 */
export interface RawInkPoint {
  x: number;
  y: number;
  p?: number; // Normalized pressure [0.0 - 1.0]
  t?: number; // Timestamp delta relative to stroke start (milliseconds)
}

/**
 * Atomic Raw Stroke
 */
export interface RawInkStroke {
  id: string;
  points: RawInkPoint[];
  color: string;
  width: number;
  timestamp?: number;
  pointCount?: number;
  flatPoints?: number[];
}

/**
 * Layer 1: Raw Vector Ink Layer
 * Independent layer storing raw points for lossless scaling, undo/redo, and high-DPI rendering.
 */
export interface RawInkLayer {
  strokes: RawInkStroke[];
}

/**
 * Layer 2: Visual AST Layer
 * Independent local semantic layer storing clustered entities, arrows, and passive metadata.
 */
export type VisualASTLayer = VisualAST;

/**
 * Layer 3: Compiled Cognitive Layer
 * Independent AI layer generated by Gemini 2.0 Flash structured outputs.
 */
export type CompiledCognitiveLayer = CompiledCognitiveMap | null;

/**
 * Cognitive Map Document Metadata
 */
export interface CognitiveMapDocumentMetadata {
  title: string;
  created_at: number;
  updated_at: number;
  vault_id?: string;
  canvas_scale?: number;
  canvas_translate_x?: number;
  canvas_translate_y?: number;
}

/**
 * Root 3-Layer .cmn Document Structure
 */
export interface CognitiveMapDocument {
  map_id: string;
  version: string; // Semantic version, e.g. "1.0.0"
  metadata: CognitiveMapDocumentMetadata;
  raw_ink_layer: RawInkLayer;
  visual_ast_layer: VisualASTLayer;
  compiled_cognitive_layer: CompiledCognitiveLayer;
}
